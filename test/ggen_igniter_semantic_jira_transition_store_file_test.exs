defmodule GgenIgniter.SemanticJiraTransitionStoreFileTest do
  @moduledoc """
  Chicago-style: the real `TransitionLog.FileStore` behind the
  `TransitionLog.Store` behaviour, in real scratch directories, real
  concurrent processes, no test doubles. Runs the shared store contract
  (`GgenIgniter.TransitionStoreCase`) plus the backward-compatibility
  falsifiers for the refactor: the on-disk layout is byte-identical to what
  the pre-behaviour implementation wrote (golden fixture generated by that
  implementation at base `dcebc42`), and the pre-existing public
  `TransitionLog.read/1` / `append/2` / `Reconciler.reconcile/3` calls with a
  bare path behave as before.
  """
  use GgenIgniter.TransitionStoreCase, async: true

  import GgenIgniter.TestSupport.SemanticJiraFixtures

  alias GgenIgniter.SemanticJira
  alias GgenIgniter.SemanticJira.Reconciler
  alias GgenIgniter.SemanticJira.TransitionLog.{FileStore, Store}

  @golden Path.expand("fixtures/transition_log_golden", __DIR__)

  setup do
    dir = Path.join(System.tmp_dir!(), "sj_store_file_#{System.unique_integer([:positive])}")
    File.rm_rf!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    %{store: dir, dir: dir}
  end

  store_contract()

  defp gold(i) do
    %{
      "kind" => "standing_transition_event",
      "identity" => "GOLD-#{i}",
      "from" => "UNKNOWN",
      "to" => "ALIVE",
      "receipt_digest" => "sha256:" <> String.pad_leading("#{i}", 64, "0"),
      "authority" => "NONE"
    }
  end

  describe "on-disk format (unchanged by the refactor)" do
    test "new FileStore writes the same bytes/names the pre-refactor log wrote", %{dir: dir} do
      for i <- 1..3, do: assert({:ok, _, :appended} = TransitionLog.append(dir, gold(i)))

      golden_names = @golden |> File.ls!() |> Enum.sort()
      assert dir |> File.ls!() |> Enum.sort() == golden_names
      assert length(golden_names) == 9

      for name <- golden_names do
        assert File.read!(Path.join(dir, name)) == File.read!(Path.join(@golden, name)),
               "byte mismatch in #{name}"
      end
    end

    test "reads a log directory written by the pre-refactor implementation", %{dir: dir} do
      File.cp_r!(@golden, dir)

      assert [%{"seq" => 1, "identity" => "GOLD-1"}, %{"seq" => 2}, %{"seq" => 3}] =
               TransitionLog.read(dir)

      # idempotent against events the old writer stored
      assert {:ok, %{"seq" => 2}, :already_recorded} = TransitionLog.append(dir, gold(2))

      # and extends it with the next seq, in the same file naming scheme
      assert {:ok, %{"seq" => 4} = fourth, :appended} = TransitionLog.append(dir, gold(4))
      digest16 = String.slice(fourth["event_digest"], 7, 16)
      assert File.exists?(Path.join(dir, "00000004-#{digest16}.json"))
      assert File.exists?(Path.join(dir, "seq-00000004.claim"))
      assert Enum.map(TransitionLog.read(dir), & &1["seq"]) == [1, 2, 3, 4]
    end

    test "read/1 of a missing directory is [] and does not create it", %{dir: dir} do
      refute File.exists?(dir)
      assert TransitionLog.read(dir) == []
      assert TransitionLog.head(dir) == 0
      refute File.exists?(dir)
    end
  end

  describe "Store.resolve/1,2" do
    test "a bare path is a FileStore, a pair and a store option select explicitly", %{dir: dir} do
      assert Store.resolve(dir) == {FileStore, dir}
      assert Store.resolve({FileStore, dir}) == {FileStore, dir}
      assert Store.resolve(dir, nil) == {FileStore, dir}
      assert Store.resolve(dir, FileStore) == {FileStore, dir}
      assert Store.resolve({FileStore, dir}, SomeOtherStore) == {FileStore, dir}
    end

    test "a struct that is not a store is refused, not silently treated as one" do
      assert_raise ArgumentError, ~r/does not implement/, fn -> Store.resolve(%URI{}) end
    end

    test "TransitionLog accepts the {module, ref} form", %{dir: dir} do
      assert {:ok, %{"seq" => 1}, :appended} = TransitionLog.append({FileStore, dir}, gold(1))
      assert [%{"seq" => 1}] = TransitionLog.read(dir)
      assert [%{"seq" => 1}] = TransitionLog.read({FileStore, dir})
    end
  end

  describe "claim protocol: released, orphaned and contended digest claims" do
    defp marker(dir, event) do
      digest = SemanticJira.digest(event)
      Path.join(dir, "digest-#{String.slice(digest, 7, 64)}.claim")
    end

    test "a duplicate parked on a claim that is then released re-claims and stores the event",
         %{dir: dir} do
      File.mkdir_p!(dir)
      claim = marker(dir, event(1))
      File.write!(claim, "")

      lenient = Task.async(fn -> TransitionLog.append(dir, event(1)) end)
      strict = Task.async(fn -> TransitionLog.append(dir, event(1), expected_seq: 5) end)
      Process.sleep(150)
      assert Task.yield(lenient, 0) == nil, "must be waiting on the claim, not returning"

      # what a strict writer that lost its seq race does
      File.rm!(claim)

      assert {:ok, %{"seq" => 1, "identity" => "X1"}, :appended} = Task.await(lenient, 30_000)
      # the strict waiter re-checked its expectation against the head it now finds
      assert {:error, {:seq_conflict, head}} = Task.await(strict, 30_000)
      assert head in [0, 1]
      assert [%{"identity" => "X1"}] = TransitionLog.read(dir)
    end

    @tag timeout: 120_000
    test "strict and lenient duplicates of losing events never see a nil event and never diverge",
         %{dir: dir} do
      for round <- 1..4 do
        d = dir <> "_r#{round}"
        on_exit(fn -> File.rm_rf!(d) end)

        jobs =
          for i <- [1, 2, 3], dup <- 1..6 do
            # a third of the duplicates are lenient, the rest strict on the same seq
            {i, if(rem(dup, 3) == 0, do: [], else: [expected_seq: 1])}
          end

        results =
          jobs
          |> Task.async_stream(
            fn {i, opts} -> {i, opts, TransitionLog.append(d, event(i), opts)} end,
            max_concurrency: length(jobs),
            timeout: 60_000
          )
          |> Enum.map(fn {:ok, r} -> r end)

        stored = TransitionLog.read(d)

        for {i, opts, res} <- results do
          case res do
            {:ok, ev, _} ->
              assert ev in stored,
                     "round #{round}: event #{i} returned but not in the log: #{inspect(ev)}"

            {:error, {:seq_conflict, _}} ->
              assert opts != [], "a lenient writer must never be refused"
          end
        end

        # every event that had a lenient duplicate is stored, exactly once, seq contiguous
        assert stored |> Enum.map(& &1["identity"]) |> Enum.sort() == ["X1", "X2", "X3"]
        assert Enum.map(stored, & &1["seq"]) == [1, 2, 3]
        assert d |> File.ls!() |> Enum.reject(&(&1 =~ ~r/\.(json|claim)\z/)) == []
      end
    end

    test "a claim orphaned by a killed writer is taken over: N duplicates store the event once",
         %{dir: dir} do
      File.mkdir_p!(dir)
      File.write!(marker(dir, event(1)), "")

      results =
        1..16
        |> Task.async_stream(
          fn _ -> TransitionLog.append(dir, event(1), claim_stale_ms: 1_000) end,
          max_concurrency: 16,
          timeout: 60_000
        )
        |> Enum.map(fn {:ok, r} -> r end)

      assert Enum.count(results, &match?({:ok, %{"identity" => "X1"}, :appended}, &1)) == 1

      assert Enum.count(results, &match?({:ok, %{"identity" => "X1"}, :already_recorded}, &1)) ==
               15

      assert [%{"seq" => 1}] = TransitionLog.read(dir)
      # the takeover lock is released and the layout is the usual one
      assert dir
             |> File.ls!()
             |> Enum.sort()
             |> Enum.map(&String.replace(&1, ~r/-[0-9a-f]+/, "-X")) ==
               ["00000001-X.json", "digest-X.claim", "seq-X.claim"]
    end

    test "an orphaned takeover lock does not block a later takeover", %{dir: dir} do
      File.mkdir_p!(dir)
      claim = marker(dir, event(1))
      File.write!(claim, "")
      File.write!(claim <> ".takeover", "")
      # a lock left by a waiter killed mid-takeover, long ago
      File.touch!(claim <> ".takeover", System.os_time(:second) - 60)

      assert {:ok, %{"seq" => 1}, :appended} =
               TransitionLog.append(dir, event(1), claim_stale_ms: 1_000)
    end

    @tag timeout: 60_000
    test "an owner that keeps touching its claim is not taken over", %{dir: dir} do
      File.mkdir_p!(dir)
      claim = marker(dir, event(1))
      File.write!(claim, "")
      # mtime has one-second resolution, so a live owner is one whose claim keeps changing
      toucher =
        Task.async(fn ->
          for _ <- 1..30 do
            File.touch!(claim)
            Process.sleep(200)
          end
        end)

      waiter = Task.async(fn -> TransitionLog.append(dir, event(1), claim_stale_ms: 2_500) end)
      assert Task.yield(waiter, 4_500) == nil, "a live owner's claim was taken over"
      Task.await(toucher, 30_000)
      assert {:ok, %{"seq" => 1}, :appended} = Task.await(waiter, 30_000)
    end
  end

  describe "events every store can hold (Store.admit/1)" do
    test "a U+0000 anywhere in an event is refused and nothing is stored", %{dir: dir} do
      for bad <- [
            %{"identity" => "a\u0000b"},
            %{"identity" => "ok", "nested" => %{"deep" => ["x", %{"k" => "y\u0000"}]}},
            %{"ke\u0000y" => "v"}
          ] do
        assert {:error, {:unstorable_event, :nul_character}} = TransitionLog.append(dir, bad)
      end

      assert TransitionLog.read(dir) == []
      assert TransitionLog.head(dir) == 0
    end
  end

  describe "Path.t() is IO.chardata: a charlist directory is a valid store spec" do
    test "TransitionLog and Reconciler accept it as before the refactor", %{dir: dir} do
      chars = String.to_charlist(dir)
      a = wo("A")

      assert TransitionLog.read(chars) == []
      assert {:ok, %{"seq" => 1} = first, :appended} = TransitionLog.append(chars, gold(1))
      assert {:ok, ^first, :already_recorded} = TransitionLog.append(dir, gold(1))
      assert TransitionLog.head(chars) == 1
      assert {:ok, ^first} = TransitionLog.get(chars, first["event_digest"])
      assert {:ok, %{"seq" => 2}, :appended} = Reconciler.reconcile(a, receipt(a), chars)

      assert {:ok, %{"seq" => 3}, :appended} =
               Reconciler.reconcile(wo("B"), receipt(wo("B")), chars, store: FileStore)

      assert Store.resolve(chars) == {FileStore, dir}
      assert Store.resolve(["x", ?/, "y"]) == {FileStore, "x/y"}
    end
  end

  describe "Reconciler.reconcile/4 store option" do
    test "defaults to the file store for a bare path; explicit forms agree", %{dir: dir} do
      a = wo("A")
      b = wo("B")
      c = wo("C")
      d = wo("D")
      d_dir = dir <> "_d"
      on_exit(fn -> File.rm_rf!(d_dir) end)

      assert {:ok, ea, :appended} = Reconciler.reconcile(a, receipt(a), dir)
      assert {:ok, eb, :appended} = Reconciler.reconcile(b, receipt(b), dir, store: FileStore)
      assert {:ok, ec, :appended} = Reconciler.reconcile(c, receipt(c), {FileStore, dir})
      assert {:ok, ed, :appended} = Reconciler.reconcile(d, receipt(d), d_dir, [])

      assert Enum.map([ea, eb, ec], & &1["seq"]) == [1, 2, 3]
      assert ed["seq"] == 1
      assert {:ok, ^ea, :already_recorded} = Reconciler.reconcile(a, receipt(a), dir)
      assert length(TransitionLog.read(dir)) == 3
    end

    test "refusals still store nothing", %{dir: dir} do
      a = wo("A")
      tampered = Map.put(a, "acceptance", ["a1", "sneaky"])

      assert {:error, {:refused, :definition_mismatch}} =
               Reconciler.reconcile(tampered, receipt(a), dir, store: FileStore)

      assert TransitionLog.read(dir) == []
    end
  end
end
