    test "every dogfood plan is a balanced s-expression bound to its graph tokens" do
      work_dir = scratch_dir!("hddl_structure")
      {output, exit_code} = run_sync(work_dir, [], "semantic-jira-pack:plan", ".hddl")

      assert exit_code == 0, "HDDL sync failed:\n#{output}"

      paths = Path.wildcard(Path.join(work_dir, "*.hddl"))
      assert length(paths) == 33

      for path <- paths do
        id = Path.basename(path, ".hddl")
        bytes = File.read!(path)

        # Comments and quoted strings carry prose; the code skeleton must be
        # balanced well-formed s-expressions on its own.
        stripped =
          bytes
          |> String.replace(~r/;;[^\n]*/, "")
          |> String.replace(~r/"(?:[^"\\]|\\.)*"/, "")

        count = fn sub -> length(String.split(stripped, sub)) - 1 end

        assert count.("(") == count.(")"),
               "#{Path.basename(path)} has unbalanced parentheses"

        assert bytes =~ "(defproblem promote-#{id} semantic-jira-workorder"
        assert bytes =~ "(workorder #{id})"
        assert bytes =~ "(projection-authority NONE)"
        assert bytes =~ "(has-receipt #{id})"
