      gall_002 = File.read!(Path.join(work_dir, "GALL-002.hddl"))
      assert gall_002 =~ "edge-002-from-001 - dependency-edge"
      assert gall_002 =~ "(depends-on GALL-002 edge-002-from-001)"
      assert gall_002 =~ "(close-court GALL-002 court-gall-002)"
      assert gall_002 =~ "(produce-evidence GALL-002 source-evidence)"
      assert gall_002 =~ "(discharge-falsifier GALL-002 falsifier-gall-002)"
