    test "the observer writes exactly one file, propositions.ttl", %{tmp: tmp} do
      assert Prose.output_files() == ["propositions.ttl"]

      out = Path.join(tmp, "out")
      assert {:ok, result} = Prose.observe(fixture_opts())
      Prose.write!(result, out)
      assert File.ls!(out) == ["propositions.ttl"]
