      refute function_exported?(Prose, :compile, 1)
      refute function_exported?(Prose, :delta_kinds, 0)
      refute function_exported?(Prose, :order_iri, 2)

      # manufacture/4 was private, so it could never be exported; pinned for
      # the documentation value of stating the deletion contract in executable
