defmodule Mix.Tasks.GgenIgniter.HandAuthored do
  # These CLI exit helpers all end in `System.halt/1`, which never returns to
  # the caller by design (real process exit codes for `--help`/invalid
  # invocation/law-refusal/blocked-render outcomes -- the same contract as
  # `Mix.Tasks.GgenIgniter.Doctor`). Dialyzer correctly observes each has no
  # local return and flags it `:no_return`; that is the intended contract
  # here, not a bug -- suppress per-function rather than leave it as an
  # unexplained "known" warning.
  @dialyzer {:no_return, print_help_and_halt: 0}
  @dialyzer {:no_return, invalid_invocation_and_halt: 2}
  @dialyzer {:no_return, refused_and_halt: 2}
  @dialyzer {:no_return, blocked_render_and_halt: 1}

  @moduledoc """
  The hand-authored-source admission task:
  `mix ggen_igniter.hand_authored <verb>` with verbs `admit`, `list`, `check`.

  Automates the exact admission law the `beam4pm-process-model-pack` (v0.1.10+)
  expresses as `bpm:HandAuthoredSource` / `bpm:AuthorshipKind` facts and
  enforces with gates `050`/`060`/`070` (`gates/*.rq`) plus the consumer's
  rendered `scripts/gate_authorship_check.sh`: every file under a manufactured
  root that carries no `GENERATED by ggen` marker is an ADMITTED, COUNTED
  exception, or the tree is refused. Every v26.9.18 parity agent performed
  this admission BY HAND in lockstep (edit ontology.ttl, get the sha wrong,
  trip REFUSED_SHA_DRIFT / REFUSED_UNADMITTED / a ceiling, re-render, rerun
  the gate); this task retires that lockstep by performing the whole lawful
  admission mechanically, validating every capability-object law BEFORE any
  byte is written.

  ## Verbs

      mix ggen_igniter.hand_authored admit --file lib/beam4pm_dfcm.ex \\
          --kind native_engine_facade \\
          --reason "why manufacturing this file is currently disproportionate" \\
          --principal "Sean Chatman (repo owner) via <session/agent>" \\
          --acceptance-command "mix test test/beam4pm_dfcm_test.exs" \\
          --sunset-plan "render from pack facts; then delete this admission" \\
          [--expires 2026-12-31] [--admitted-at-commit abc1234]
          [--acceptance-prerequisite path-or-cmd:...] [--no-render]

      mix ggen_igniter.hand_authored list   [--ontology ...] [--pack-dir ...]

      mix ggen_igniter.hand_authored check  [--gate-script scripts/gate_authorship_check.sh]

  ### `admit`

  Validates, in order (cheapest, highest-information gate first), and refuses
  with a typed one-line `REFUSED_*` code + exit 1 on the first failure:

  1. `REFUSED_ONTOLOGY_NOT_FOUND` / `REFUSED_PACK_ONTOLOGY_NOT_FOUND` -- the
     consumer's `ontology.ttl` (default `./ontology.ttl`) / the pack's
     ontology (default
     `vendor/ggen-marketplace/packs/beam4pm-process-model-pack/ontology.ttl`)
     must exist.
  2. `REFUSED_FILE_NOT_FOUND` -- the admitted file must exist on disk (the
     sha256 is computed over the REAL bytes, never asserted).
  3. `REFUSED_MARKED_FILE` -- the file's first 3 lines must NOT carry the
     `GENERATED by ggen` marker (admitting a manufactured file is the gate's
     REFUSED_CONTRADICTION, caught before it can be committed).
  4. `REFUSED_MISSCOPED` -- the path must sit under a manufactured root
     (`src lib gleam/src gleam/test test schema docs/reference
     infra/gcp/cloudrun infra/gcp/packer`, the gate script's own ROOTS list;
     `--roots` overrides).
  5. `REFUSED_MISSING_ACCEPTANCE_COMMAND` -- every admission needs a real
     acceptance command (gate 050 requires `bpm:acceptanceCommand` for ALL
     kinds, debt or not).
  6. `REFUSED_INVALID_EXPIRY` -- `--expires` must be `YYYY-MM-DD` when given
     (the manifest renders the raw literal; the shell gate string-compares it
     against today).
  7. `REFUSED_UNKNOWN_KIND` -- `--kind` must name an admitted
     `bpm:AuthorshipKind` in the PACK's closed vocabulary (anti-join law of
     gate 060, evaluated here before writing, not after).
  8. `REFUSED_MISSING_SUNSET_PLAN` / `REFUSED_MISSING_EXPIRY` -- kinds whose
     `bpm:countsAsDebt` is `"true"` must carry `--sunset-plan` and `--expires`
     (gate 050: a path-only debt admission is a standing grant).
  9. `REFUSED_DUPLICATE_SOURCE_PATH` -- no existing `bpm:HandAuthoredSource`
     individual may already admit the same `bpm:sourcePath` (gate 060's
     duplicate law; a duplicate would double-count the debt).
  10. `REFUSED_CEILING_EXCEEDED` -- the kind's current admitted count + 1 must
      not exceed its `bpm:debtCeiling` (gate 070's law, with the pack-edit
      remedy named: raising a ceiling is a reviewed edit to the PACK's
      ontology.ttl, never an ambient grant).
  11. `REFUSED_MISSING_FIELD` -- `--principal`, `--reason`, and an admitted-at
      commit (`--admitted-at-commit` or `git rev-parse --short HEAD` in the
      consumer tree) must all resolve (gate 050's required-field set).
  12. `REFUSED_ONTOLOGY_UNPARSEABLE` -- both ontologies must parse as real
      Turtle; `REFUSED_SUBJECT_PREFIX_UNDECLARED` -- the subject namespace
      prefix (default `bap`, `--subject-prefix`) must already be declared in
      the consumer ontology.

  Only then is the new individual appended to the consumer's ontology.ttl --
  directly after the LAST existing `bpm:HandAuthoredSource` individual (or at
  end-of-file when the graph admits none yet; Turtle `@prefix` declarations
  are positional, and both anchors are after the consumer's own prefix
  declarations). The write is a single `File.write!` of the full modified
  content (the same direct-write contract `GgenIgniter.DoctorFixes` uses; see
  its `--dry-run` note). The individual carries exactly the capability-object
  fields the gates require: debt kinds get `bpm:contentSha256` (lowercase hex
  over the real bytes), `bpm:admissionExpires`, `bpm:sunsetPlan`; non-debt
  kinds get none of the three (the manifest renders `-`, matching the
  consumer convention for `manufacturing_input` / `reference_evidence` rows).

  Then, unless `--no-render` was passed, the pack render is triggered: the
  three hand-authored projections
  (`schema/beam4pm_hand_authored_source.tsv`, `docs/reference/
  beam4pm_hand_authored_source.md`, `test/beam4pm_authorship_gate_test.exs`)
  are Tera templates rendered by the Rust `ggen sync run` (NOT
  `mix ggen_igniter.sync` -- that is the EEx/Ash leg and renders none of
  these). Because none of the three templates carries `force: true`, ggen's
  write policy (FM-WRITE-005) refuses to overwrite an existing target, so the
  task applies the same procedure the v26.9.18 integration used and
  documented in its synthesis commit: temporarily scaffold `force: true` into
  the three templates' front matter, run `ggen sync run`, then restore the
  template bytes verbatim (a failed restore is
  `RENDER_TEMPLATE_RESTORE_FAILED`, exit 1). If the `ggen` binary is not on
  PATH the admission itself still stands (ontology.ttl is already written)
  and the task prints the exact two-step commands instead --
  `BLOCKED_RENDER_NO_GGEN`, exit 3. If ggen refuses on a pack-content-hash
  mismatch (FM-PACK-008: the ceilings were just raised in the vendored pack),
  its own remediation is `rm -f ggen.lock && ggen sync run` (re-lock) --
  printed verbatim on failure, never attempted silently.

  Under the global `--dry-run`, NOTHING is written and nothing is rendered:
  every validation above still really runs, and the task prints the individual
  it WOULD append (with its real sha256) plus `DRY-RUN: no files written`.

  ### `list`

  Loads consumer + pack ontologies, prints the admitted set grouped per kind
  (count / ceiling, `AT CEILING` flagged), one row per admission (path, kind,
  debt, sha-bound, expiry), then really runs the pack's own gate queries
  `050`/`060`/`070` (`gates/*.rq`) through the oxigraph engine over the merged
  consumer+pack graph. Exit 1 iff any gate query returns a row (the graph
  itself violates the law) -- this is the pre-render, pre-shell-gate
  half of `check`, usable against the graph alone.

  ### `check`

  Runs the consumer's rendered shell gate (default
  `scripts/gate_authorship_check.sh`) as a real subprocess against the real
  tree, streaming its output, and exits with the gate's own exit code. This is
  the decisive, observed gate: manifest vs `git ls-files`, sha drift, expiry,
  acceptance exercise (`--exercise` is the gate script's own flag; pass it via
  `--gate-arg`).

  ## Exit codes

  - `0` -- admit/list/check succeeded (under `admit --dry-run`: validated,
    nothing written).
  - `1` -- a typed `REFUSED_*` law refusal (nothing was written), a gate row
    from `list`, a failing `check` gate, or a failed template restore.
  - `2` -- invalid invocation: unknown verb, unknown flag, missing
    `--file`/`--kind`, or a verb omitted.
  - `3` -- unsupported capability on this host: render requested but the
    `ggen` binary is absent (the two-step manual commands are printed).
  """

  use Igniter.Mix.Task

  alias GgenIgniter.Query.Oxigraph

