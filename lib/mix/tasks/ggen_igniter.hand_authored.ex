  defp subject_for(merged, prefix, path) do
    base = "hand_authored_" <> slug(path)
    existing = existing_subjects(merged)

    Enum.find_value(0..200, fn i ->
      name = if i == 0, do: base, else: "#{base}_#{i}"
      full = "#{prefix}:#{name}"
      if MapSet.member?(existing, full), do: nil, else: full
    end) ||
      raise RuntimeError,
        message:
          "REFUSED_SUBJECT_EXHAUSTED: no free subject under #{prefix}:#{base} after 200 attempts"
  end

  defp existing_subjects(merged) do
    query = """
    PREFIX bpm: <https://ggen.dev/ontology/beam-process-model#>
    SELECT ?h WHERE { ?h a bpm:HandAuthoredSource . }
    """

    Oxigraph.run(merged, query)
    |> MapSet.new(fn row ->
      iri = cell(row, "h")
      iri |> String.split("#") |> List.last() |> String.split("/") |> List.last()
    end)
  end

  defp slug(path) do
    path
    |> String.downcase()
    |> String.replace(~r/[^a-z0-9]+/, "_")
    |> String.trim("_")
  end

  defp ttl_block(ind) do
    # Property order matches the reference consumer's own individual blocks:
    # sourcePath, authorshipKind, principal, reason, acceptanceCommand,
    # [acceptancePrerequisite], [contentSha256], admittedAtCommit,
    # [admissionExpires], [sunsetPlan]. Debt kinds always carry sha256 +
    # expiry + sunset plan (gate 050); non-debt kinds carry none of the three
    # UNLESS the caller explicitly provided an expiry (the gate allows it, and
    # silently dropping a caller-provided fact would be dishonest).
    prop_lines =
      [
        prop("bpm:sourcePath", ind.path),
        kind_line(ind.kind_iri),
        prop("bpm:authorizingPrincipal", ind.principal),
        prop("bpm:admissionReason", ind.reason),
        prop("bpm:acceptanceCommand", ind.acceptance_command)
      ] ++
        maybe_prop(ind.acceptance_prerequisite, "bpm:acceptancePrerequisite") ++
        if(ind.debt, do: ["    bpm:contentSha256 \"#{ind.sha}\" ;"], else: []) ++
        ["    bpm:admittedAtCommit \"#{ind.admitted_at}\" ;"] ++
        maybe_prop(ind.expires, "bpm:admissionExpires") ++
        if(ind.debt, do: ["    bpm:sunsetPlan \"#{ttl_escape(ind.sunset_plan)}\" ."], else: [])

    lines = ["#{ind.subject} a bpm:HandAuthoredSource ;" | prop_lines]

    fix_terminators(lines)
    |> Enum.join("\n")
  end

  defp prop(name, value), do: "    #{name} \"#{ttl_escape(value)}\" ;"
  defp kind_line(iri), do: "    bpm:authorshipKind #{iri_literal(iri)} ;"

  defp maybe_prop(nil, _name), do: []
  defp maybe_prop("", _name), do: []
  defp maybe_prop(value, name), do: [prop(name, value)]

  # The last emitted property must terminate with " ." and every other line
  # with " ;" -- independent of which optional lines were emitted. Strip any
  # trailing terminator/whitespace first, then append the right one, so a
  # line authored without a terminator can never slip through.
  defp fix_terminators(lines) do
    lines
    |> Enum.with_index()
    |> Enum.map(fn {line, i} ->
      last? = i == length(lines) - 1

      bare =
        line
        |> String.trim_trailing()
        |> String.trim_trailing(";")
        |> String.trim_trailing(".")
        |> String.trim_trailing()

      if last?, do: bare <> " .", else: bare <> " ;"
    end)
  end

  defp insert_individual(content, ind) do
    lines = String.split(content, "\n")
    block = ttl_block(ind)

    last_idx =
      lines
      |> Enum.with_index()
      |> Enum.filter(fn {line, _i} -> String.contains?(line, "a bpm:HandAuthoredSource") end)
      |> Enum.map(fn {_line, i} -> i end)
      |> List.last()

    case last_idx do
      nil ->
        # No existing individual to anchor on: append at end-of-file. Turtle
        # @prefix declarations are positional but apply to the whole rest of
        # the file, so any prefix declared anywhere earlier is in scope here
        # (and prefix_declared?/2 already verified the subject prefix exists).
        new_content = String.trim_trailing(content, "\n") <> "\n\n" <> block <> "\n"
        {new_content, "appended at end-of-file (no existing bpm:HandAuthoredSource individual)"}

      last_idx ->
        # The block ends at the first line whose trimmed form terminates with
        # "." -- either a standalone "." line or (the reference consumer's own
        # style) the final property line ending inline in " .". The opening
        # line ends with " ;", never ".", so it can never match itself.
        dot_idx =
          lines
          |> Enum.slice(last_idx..-1//1)
          |> Enum.with_index()
          |> Enum.find(fn {line, _} ->
            trimmed = String.trim(line)
            trimmed != "" and String.ends_with?(trimmed, ".")
          end)
          |> case do
            nil ->
              refused_and_halt(
                "REFUSED_ONTOLOGY_MALFORMED_SECTION",
                "no terminating '.' after the last bpm:HandAuthoredSource individual"
              )

            {_line, rel} ->
              last_idx + rel
          end

        # head = everything before the dot line; tail = [dot_line | rest]
        # (rest may be [] when the dot line is the file's last line -- no
        # trailing newline -- so split/Enum.at, never a [dot_line | rest]
        # match). head/dot_line/rest partition the lines exactly once.
        {head, tail} = Enum.split(lines, dot_idx)
        dot_line = Enum.at(tail, 0)
        rest = Enum.drop(tail, 1)

        # The join must end with exactly one trailing newline: a consumer
        # file that does NOT end in a newline (the reference consumer's own
        # ontology.ttl is one) would otherwise leave the new block's final
        # "." line as the last element with no newline, and the NEXT admit's
        # terminator scan would then anchor on it with nothing after it.
        new_content =
          [head, [dot_line, ""], [block], rest]
          |> Enum.concat()
          |> Enum.join("\n")
          |> then(&(String.trim_trailing(&1, "\n") <> "\n"))

        anchor_subject = lines |> Enum.at(last_idx) |> String.split(" ") |> List.first()
        {new_content, "inserted after #{anchor_subject}"}
    end
  end

  defp ttl_escape(s) do
    String.replace(s, ~r{["\\\n\t]}, fn
      "\"" -> "\\\""
      "\\" -> "\\\\"
      "\n" -> "\\n"
      "\t" -> "\\t"
      c -> c
    end)
  end

